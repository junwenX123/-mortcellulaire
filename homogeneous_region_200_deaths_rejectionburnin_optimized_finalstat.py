def make_scenarios(base: Params) -> Dict[str, Params]:
    """
    Parameter changes around the homogeneous baseline, keeping the same
    rejection sampling / thinning structure.

    Goal:
      - reduce death rejection rate,
      - keep the same biological acceptance rule:
            death accepted iff inside active zone and outside ERK protection,
      - compare parameter effects after burn-in.
    """
    return {
        "baseline": base,

        # More death candidates: mostly changes speed, not necessarily rejection rate.
        "higher_death_intensity": replace(
            base,
            name="higher_death_intensity",
            seed=124,
            lambda_d=0.35,
        ),

        # Increase active-zone coverage:
        # beta_a_R smaller -> larger active radius on average.
        # beta_a_T smaller -> longer active lifetime on average.
        # lambda_a_1 larger -> more activation candidates.
        "more_active_coverage": replace(
            base,
            name="more_active_coverage",
            seed=125,
            lambda_a_1=1.00,
            beta_a_R=1.00,
            beta_a_T=0.60,
        ),

        # Weaker ERK protection:
        # beta_d_R larger -> smaller ERK radius on average.
        # beta_d_T larger -> shorter ERK duration on average.
        "weaker_ERK": replace(
            base,
            name="weaker_ERK",
            seed=126,
            beta_d_R=2.50,
            beta_d_T=1.50,
        ),

        # Balanced optimization:
        # active zones are slightly larger/longer,
        # ERK protection is weaker,
        # but parameters are not too extreme.
        "balanced_optimized": replace(
            base,
            name="balanced_optimized",
            seed=127,
            lambda_a_1=1.00,
            beta_a_R=1.00,
            beta_a_T=0.60,
            beta_d_R=2.50,
            beta_d_T=1.50,
        ),

        # Stronger optimization test:
        # use this only if death rejection is still too high.
        "low_rejection_test": replace(
            base,
            name="low_rejection_test",
            seed=128,
            lambda_a_1=1.20,
            lambda_a_c=0.08,
            beta_a_R=0.90,
            beta_a_T=0.50,
            beta_d_R=3.00,
            beta_d_T=2.00,
        ),
    }


