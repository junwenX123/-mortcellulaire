def write_analysis_report(rows: List[Dict[str, Any]], out_dir: Path, colorbar_vmax: int) -> Path:
    path = out_dir / "spatial_uniformity_analysis_report_homogeneous_200.md"
    if not rows:
        path.write_text("No results.\n", encoding="utf-8")
        return path

    first = rows[0]
    n = int(first["n_observed_deaths_analyzed"])
    bins_plot = int(first["spatial_bins_per_axis_for_plot"])
    k_plot = bins_plot * bins_plot
    bins_chi2 = int(first["spatial_bins_per_axis_for_chi2_test"])
    k_chi2 = bins_chi2 * bins_chi2
    df_chi2 = k_chi2 - 1
    expected_plot = n / k_plot
    expected_chi2 = n / k_chi2
    cv_ref = math.sqrt((k_plot - 1) / n)
    sd_reduced = math.sqrt(2.0 / df_chi2)

    lines: List[str] = []
    lines.append("# Homogeneous-region observed death analysis after burn-in\n\n")
    lines.append(f"All 2D histograms use the same colorbar scale: 0 to {colorbar_vmax} observed deaths per bin.\n\n")
    lines.append(
        f"The simulation keeps the rejection sampling / thinning structure. "
        f"The first {int(first['burn_in_deaths'])} observed deaths are used as burn-in and are not used for statistics. "
        f"The reported statistics use the next {n} observed deaths.\n\n"
    )

    lines.append("## Mathematical/statistical interpretation\n\n")
    lines.append("### Spatial coefficient of variation\n\n")
    lines.append(
        "Let the spatial window be divided into equal-area bins and let `H_i` be the observed death count in bin `i`. "
        "The spatial coefficient of variation is\n\n"
    )  
    lines.append(
        "$$ CV_{\\mathrm{space}} = \\frac{\\mathrm{sd}(H_1,\\ldots,H_k)}{\\mathrm{mean}(H_1,\\ldots,H_k)} $$\n\n"
    )
    lines.append(
        "Under spatial uniformity, the bin counts are approximately multinomial with probability `1/k` per bin. "
        "Thus a useful finite-sample reference is\n\n"
    )
    lines.append(
        "$$\n"
        "CV_{\\mathrm{uniform}}\n"
        "\\approx\n"
        "\\sqrt{\\frac{k-1}{n}}.\n"
        "$$\n\n"
    )
    
    lines.append(
        f"For the {bins_plot} x {bins_plot} plot grid, `k = {k_plot}` and `n = {n}`, so "
        f"`CV_uniform ≈ sqrt(({k_plot}-1)/{n}) = {cv_ref:.3f}`. "
        "The ratio `CV_observed / CV_uniform` is therefore easier to interpret than the raw CV alone.\n\n"
    )

    lines.append("### Chi-square uniformity test\n\n")
    lines.append(
        f"The {bins_plot} x {bins_plot} grid is useful for visualization, but its expected count under uniformity is "
        f"`{n}/{k_plot} = {expected_plot:.2f}` per bin. "
        f"For the formal chi-square test, the script uses a coarser {bins_chi2} x {bins_chi2} grid, "
        f"where the expected count is `{n}/{k_chi2} = {expected_chi2:.2f}` per bin.\n\n"
    )
    lines.append("The Pearson statistic is\n\n")
    lines.append(
        "$$ X^2 = \\sum_{i=1}^{k} \\frac{(O_i-E_i)^2}{E_i} $$\n\n"
    )
    lines.append(
        f"Under spatial uniformity, `X^2` is approximately chi-square with `df = k-1 = {df_chi2}` degrees of freedom. "
        f"Therefore `X^2/df` should fluctuate around 1, with standard deviation approximately "
        f"`sqrt(2/df) = {sd_reduced:.3f}`. "
        "The p-value is the right-tail probability `P(chi2_df >= X_obs^2)`.\n\n"
    )

    lines.append("## Results\n\n")
    lines.append(
        "| scenario | time for analyzed 200 deaths | death rejection rate | outside-active rejection | ERK rejection | CV ratio to uniform | chi2/df | p-value | empty bins |\n"
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|\n"
    )
    for r in rows:
        lines.append(
            f"| {r['scenario']} | "
            f"{float(r['total_time_for_analyzed_200_deaths_after_burnin']):.3f} | "
            f"{float(r['death_rejection_rate']):.3f} | "
            f"{float(r['death_rejection_rate_outside_active']):.3f} | "
            f"{float(r['death_rejection_rate_by_erk']):.3f} | "
            f"{float(r['spatial_cv_ratio_to_uniform_plot_bins']):.3f} | "
            f"{float(r['spatial_chi2_per_df_chi2_bins']):.3f} | "
            f"{float(r['spatial_chi2_p_value_chi2_bins']):.3g} | "
            f"{int(r['spatial_empty_bins_plot_bins'])} |\n"
        )


    baseline = rows[0]
    fastest = min(rows, key=lambda r: float(r["total_time_for_analyzed_200_deaths_after_burnin"]))
    strongest_hetero = max(rows, key=lambda r: float(r["spatial_cv_ratio_to_uniform_plot_bins"]))
    lines.append("\n## Short conclusion\n\n")
    lines.append(
        f"The baseline analyzes exactly {int(baseline['n_observed_deaths_analyzed'])} deaths after burn-in. "
        f"Its CV ratio is {float(baseline['spatial_cv_ratio_to_uniform_plot_bins']):.3f}; "
        "values close to 1 are compatible with uniform multinomial fluctuations on the plotting grid.\n\n"
    )
    lines.append(
        f"The fastest scenario is `{fastest['scenario']}`, with "
        f"{float(fastest['total_time_for_analyzed_200_deaths_after_burnin']):.3f} time units for the analyzed 200 deaths.\n\n"
    )
    lines.append(
        f"The largest spatial CV ratio is obtained by `{strongest_hetero['scenario']}`, "
        f"with CV ratio {float(strongest_hetero['spatial_cv_ratio_to_uniform_plot_bins']):.3f}.\n"
    )

    path.write_text("".join(lines), encoding="utf-8")
    return path


def make_zip(out_dir: Path) -> Path:
    zip_path = out_dir.with_suffix(".zip")
    if zip_path.exists():
        zip_path.unlink()
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for file in out_dir.rglob("*"):
            if file.is_file():
                zf.write(file, arcname=file.relative_to(out_dir.parent))
    return zip_path


