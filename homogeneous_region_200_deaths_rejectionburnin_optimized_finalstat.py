"""
Rejection sampling / thinning simulation for the homogeneous-region  model
with ERK negative feedback.

Workflow implemented here:
  1. Keep the rejection sampling / thinning structure.
  2. Use the same left-limit conventions as the consistent animation script:
       - active zone A(V^a_{s-}): S_i^a < s <= S_i^a + T_i^a,
       - ERK protected zone A(V^p_{s-}): S_j^d < s <= S_j^d + T_j^d.
  3. Burn-in first, by default 500 observed deaths.
  4. Then collect and analyze the next 200 observed deaths.
  5. Stop as soon as burn_in_deaths + target_deaths observed deaths are accepted.
  6. Save statistics on the analyzed observed death process:
       - number of analyzed observed deaths,
       - time needed for the analyzed 200 deaths after burn-in,
       - mean / median inter-death time after burn-in,
       - death-candidate rejection rates,
       - spatial coefficient of variation with a uniform reference,
       - Pearson chi-square uniformity test on a coarser grid.
  7. Plot a histogram in time after burn-in.
  8. Plot a 2D histogram in space with a common colorbar scale across scenarios.
  9. Play with several parameter sets and save a comparison CSV file.

"""

