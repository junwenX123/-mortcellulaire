@dataclass(frozen=True)
class Params:
    name: str = "baseline"
    seed: int = 123

    # Spatial window W = [0, Lx] x [0, Ly]
    Lx: float = 10.0
    Ly: float = 10.0

    # Rejection-sampling simulation is generated by finite candidate blocks.
    # The true stopping time is the time of death number burn_in_deaths + target_deaths.
    block_duration: float = 10.0
    max_blocks: int = 2000

    # Burn-in and target.
    # Statistics are computed only for the target_deaths after burn-in.
    burn_in_deaths: int = 500
    target_deaths: int = 200

    # Activation process V^a_t.
    # lambda_a_1 is the dominating candidate intensity on W.
    # lambda_a_c is the background intensity outside active zones.
    lambda_a_1: float = 0.60
    lambda_a_c: float = 0.05

    # Activation marks: R^a ~ Exp(beta_a_R), T^a ~ Exp(beta_a_T).
    beta_a_R: float = 1.4
    beta_a_T: float = 0.8

    # Candidate death process Phi^d on W.
    lambda_d: float = 0.25

    # Protection marks after accepted deaths: R^d ~ Exp(beta_d_R), T^d ~ Exp(beta_d_T).
    beta_d_R: float = 1.2
    beta_d_T: float = 0.6

    # Plotting/statistics choices.
    # With only 200 analyzed deaths, 10 x 10 is useful for visualization and CV.
    # A coarser 5 x 5 grid gives expected count 200/25 = 8 for the chi-square test.
    time_bins: int = 20
    space_bins: int = 10
    chi2_bins: int = 5

    @property
    def area_W(self) -> float:
        return self.Lx * self.Ly

    @property
    def total_deaths_to_simulate(self) -> int:
        return self.burn_in_deaths + self.target_deaths


@dataclass
class SimulationResult:
    name: str
    params: Params

    # All accepted observed deaths, including burn-in.
    death_x_all: np.ndarray
    death_y_all: np.ndarray
    death_t_all: np.ndarray

    # Analyzed observed deaths, after burn-in.
    death_x: np.ndarray
    death_y: np.ndarray
    death_t: np.ndarray              # raw time values
    death_t_since_burnin: np.ndarray # time relative to burn-in end

    # Accepted activation centers, historical.
    activation_x: np.ndarray
    activation_y: np.ndarray
    activation_t: np.ndarray

    burn_in_time: float
    final_time: float
    analysis_time_span: float

    target_deaths: int
    burn_in_deaths_requested: int
    total_deaths_simulated: int
    observed_deaths_analyzed: int
    stopped_by_target: bool

    activation_candidates_processed: int
    activation_accepted: int
    activation_rejected: int

    death_candidates_processed: int
    death_rejected_outside_active: int
    death_rejected_by_erk: int
    erk_zones_created_total: int


