# 2. Geometry: active and protected zones
# ============================================================


def validate_params(p: Params) -> None:
    if not (0.0 <= p.lambda_a_c < p.lambda_a_1):
        raise ValueError("Need 0 <= lambda_a_c < lambda_a_1 for rejection sampling.")
    for key in ["beta_a_R", "beta_a_T", "lambda_d", "beta_d_R", "beta_d_T"]:
        if getattr(p, key) <= 0:
            raise ValueError(f"Need {key} > 0.")
    if p.Lx <= 0 or p.Ly <= 0:
        raise ValueError("Need positive domain size.")
    if p.block_duration <= 0 or p.max_blocks <= 0:
        raise ValueError("Need positive block_duration and max_blocks.")
    if p.burn_in_deaths < 0 or p.target_deaths <= 0:
        raise ValueError("Need burn_in_deaths >= 0 and target_deaths > 0.")
    if p.space_bins <= 0 or p.chi2_bins <= 0 or p.time_bins <= 0:
        raise ValueError("Need positive histogram bin numbers.")


def point_in_active_zone_lists(
    x: float,
    y: float,
    s: float,
    X_acc: List[float],
    Y_acc: List[float],
    S_acc: List[float],
    R_acc: List[float],
    Tau_acc: List[float],
) -> bool:
    """
    Return True if (x,y) belongs to A(V^a_{s-}).

    Consistent left-limit convention:
        S_i^a < s <= S_i^a + T_i^a.
    The strict inequality S_i^a < s prevents a candidate from accepting itself.
    """
    for xk, yk, sk, rk, tauk in zip(X_acc, Y_acc, S_acc, R_acc, Tau_acc):
        if sk < s <= sk + tauk:
            if (x - xk) ** 2 + (y - yk) ** 2 <= rk ** 2:
                return True
    return False


def point_in_protected_zone_lists(
    x: float,
    y: float,
    s: float,
    X_death: List[float],
    Y_death: List[float],
    S_death: List[float],
    R_death: List[float],
    Tau_death: List[float],
) -> bool:
    """
    Return True if (x,y) belongs to A(V^p_{s-}).

    Consistent left-limit convention:
        S_j^d < s <= S_j^d + T_j^d.
    """
    for xj, yj, sj, rj, tauj in zip(X_death, Y_death, S_death, R_death, Tau_death):
        if sj < s <= sj + tauj:
            if (x - xj) ** 2 + (y - yj) ** 2 <= rj ** 2:
                return True
    return False


# ============================================================
# 3. Rejection sampling / thinning simulation
# ============================================================


def simulate_one(p: Params) -> SimulationResult:
    """
    Simulate until burn_in_deaths + target_deaths observed deaths are accepted.

    Candidate activations are generated on each block, accepted
    recursively in chronological order, and candidate deaths are then tested
    against A(V^a_{s-}) and A(V^p_{s-}).
    """
    validate_params(p)
    rng = np.random.default_rng(p.seed)

    # Accepted activation centers V^a.
    X_acc: List[float] = []
    Y_acc: List[float] = []
    S_acc: List[float] = []
    R_acc: List[float] = []
    Tau_acc: List[float] = []

    # Accepted observed deaths V^d and their ERK marks V^p.
    X_death: List[float] = []
    Y_death: List[float] = []
    S_death: List[float] = []
    R_death: List[float] = []
    Tau_death: List[float] = []

    activation_candidates_processed = 0
    activation_rejected = 0
    death_candidates_processed = 0
    death_rejected_outside_active = 0
    death_rejected_by_erk = 0

    t0 = 0.0

    def point_in_active_zone_arrays(
        x: float,
        y: float,
        s: float,
        X_arr: np.ndarray,
        Y_arr: np.ndarray,
        S_arr: np.ndarray,
        R_arr: np.ndarray,
        Tau_arr: np.ndarray,
    ) -> bool:
        """Vectorized test for (x,y) in A(V^a_{s-})."""
        if len(X_arr) == 0:
            return False
        active_before_s = (S_arr < s) & (s <= S_arr + Tau_arr)
        if not np.any(active_before_s):
            return False
        dx = x - X_arr[active_before_s]
        dy = y - Y_arr[active_before_s]
        rr = R_arr[active_before_s]
        return bool(np.any(dx * dx + dy * dy <= rr * rr))

    for _block in range(p.max_blocks):
        t1 = t0 + p.block_duration

        # ----------------------------------------------------
        # A) Candidate activations in W x [t0,t1]
        # ----------------------------------------------------
        n_act = int(rng.poisson(p.lambda_a_1 * p.area_W * p.block_duration))
        activation_candidates_processed += n_act

        act_x = rng.uniform(0.0, p.Lx, size=n_act)
        act_y = rng.uniform(0.0, p.Ly, size=n_act)
        act_s = rng.uniform(t0, t1, size=n_act)
        act_u = rng.uniform(0.0, 1.0, size=n_act)
        act_r = rng.exponential(scale=1.0 / p.beta_a_R, size=n_act)
        act_tau = rng.exponential(scale=1.0 / p.beta_a_T, size=n_act)

        for idx in np.argsort(act_s):
            x = float(act_x[idx])
            y = float(act_y[idx])
            s = float(act_s[idx])
            u = float(act_u[idx])
            r = float(act_r[idx])
            tau = float(act_tau[idx])

            inside_active = point_in_active_zone_lists(x, y, s, X_acc, Y_acc, S_acc, R_acc, Tau_acc)

            # Rejection / thinning rule from the consistent script:
            # p^a_v(x) = 1 if x in A(v), lambda_a_c / lambda_a_1 otherwise.
            if inside_active or (u <= p.lambda_a_c / p.lambda_a_1):
                X_acc.append(x)
                Y_acc.append(y)
                S_acc.append(s)
                R_acc.append(r)
                Tau_acc.append(tau)
            else:
                activation_rejected += 1

        # Convert accepted activations once per block for fast death tests.
        X_acc_arr = np.asarray(X_acc)
        Y_acc_arr = np.asarray(Y_acc)
        S_acc_arr = np.asarray(S_acc)
        R_acc_arr = np.asarray(R_acc)
        Tau_acc_arr = np.asarray(Tau_acc)

        # ----------------------------------------------------
        # B) Candidate deaths in W x [t0,t1]
        # ----------------------------------------------------
        n_death_star = int(rng.poisson(p.lambda_d * p.area_W * p.block_duration))

        d_x = rng.uniform(0.0, p.Lx, size=n_death_star)
        d_y = rng.uniform(0.0, p.Ly, size=n_death_star)
        d_s = rng.uniform(t0, t1, size=n_death_star)
        d_r = rng.exponential(scale=1.0 / p.beta_d_R, size=n_death_star)
        d_tau = rng.exponential(scale=1.0 / p.beta_d_T, size=n_death_star)

        for idx in np.argsort(d_s):
            if len(S_death) >= p.total_deaths_to_simulate:
                break

            xd = float(d_x[idx])
            yd = float(d_y[idx])
            sd = float(d_s[idx])
            rd = float(d_r[idx])
            taud = float(d_tau[idx])

            death_candidates_processed += 1

            inside_active = point_in_active_zone_arrays(
                xd, yd, sd, X_acc_arr, Y_acc_arr, S_acc_arr, R_acc_arr, Tau_acc_arr
            )
            inside_protected = point_in_protected_zone_lists(
                xd, yd, sd, X_death, Y_death, S_death, R_death, Tau_death
            )

            # Observed death is accepted iff it is inside active zones and outside ERK protection.
            if inside_active and not inside_protected:
                X_death.append(xd)
                Y_death.append(yd)
                S_death.append(sd)
                R_death.append(rd)
                Tau_death.append(taud)
            else:
                if inside_protected:
                    death_rejected_by_erk += 1
                else:
                    death_rejected_outside_active += 1

        if len(S_death) >= p.total_deaths_to_simulate:
            break

        t0 = t1
    else:
        raise RuntimeError(
            f"Only {len(S_death)} observed deaths after {p.max_blocks} blocks. "
            "Increase block_duration, max_blocks, lambda_d, or activation parameters."
        )

    # Keep exactly burn-in + target deaths.
    X_all = np.asarray(X_death[:p.total_deaths_to_simulate])
    Y_all = np.asarray(Y_death[:p.total_deaths_to_simulate])
    S_all = np.asarray(S_death[:p.total_deaths_to_simulate])

    if len(S_all) > p.burn_in_deaths:
        burn_in_time = 0.0 if p.burn_in_deaths == 0 else float(S_all[p.burn_in_deaths - 1])
        X_an = X_all[p.burn_in_deaths:]
        Y_an = Y_all[p.burn_in_deaths:]
        S_an = S_all[p.burn_in_deaths:]
        S_since_burnin = S_an - burn_in_time
        analysis_time_span = float(S_all[-1] - burn_in_time) if len(S_an) else 0.0
    else:
        burn_in_time = float(S_all[-1]) if len(S_all) else 0.0
        X_an = np.array([])
        Y_an = np.array([])
        S_an = np.array([])
        S_since_burnin = np.array([])
        analysis_time_span = 0.0

    return SimulationResult(
        name=p.name,
        params=p,
        death_x_all=X_all,
        death_y_all=Y_all,
        death_t_all=S_all,
        death_x=X_an,
        death_y=Y_an,
        death_t=S_an,
        death_t_since_burnin=S_since_burnin,
        activation_x=np.asarray(X_acc),
        activation_y=np.asarray(Y_acc),
        activation_t=np.asarray(S_acc),
        burn_in_time=burn_in_time,
        final_time=float(S_all[-1]) if len(S_all) else 0.0,
        analysis_time_span=analysis_time_span,
        target_deaths=p.target_deaths,
        burn_in_deaths_requested=p.burn_in_deaths,
        total_deaths_simulated=len(S_all),
        observed_deaths_analyzed=len(S_an),
        stopped_by_target=(len(S_all) >= p.total_deaths_to_simulate),
        activation_candidates_processed=activation_candidates_processed,
        activation_accepted=len(X_acc),
        activation_rejected=activation_rejected,
        death_candidates_processed=death_candidates_processed,
        death_rejected_outside_active=death_rejected_outside_active,
        death_rejected_by_erk=death_rejected_by_erk,
        erk_zones_created_total=len(S_all),
    )


